console.log(`q0 = ${q[0].toFixed(6)}  e0(model) = ${e0.toFixed(3)} (WHO ${e0Row.value.toFixed(3)})  e85 = ${e85For(B).toFixed(4)} (WHO ${E85.toFixed(4)})`);
console.log(`mean completed lifespan = ${mean.toFixed(3)}`);
console.log(`S(5) = ${surv[5].toFixed(4)}  S(18) = ${surv[18].toFixed(4)}  S(65) = ${surv[65].toFixed(4)}  S(80) = ${surv[80].toFixed(4)}  S(90) = ${surv[90].toFixed(4)}`);
console.log(`S(100) = ${surv[100].toExponential(3)}  S(110) = ${surv[110].toExponential(3)}  S(122) = ${surv[122].toExponential(3)}`);
console.log(`q85 = ${q[85].toFixed(3)}  q95 = ${q[95].toFixed(3)}  q100 = ${q[100].toFixed(3)}  q110 = ${q[110].toFixed(3)}`);
